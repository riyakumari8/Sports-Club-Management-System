package com.clubsphere.shop.entity;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

/**
 * ProductCategory — Entity representing top-level product groupings in the Sports Shop.
 *
 * Examples: "Sports Rackets", "Cricket Equipment", "Tennis Balls", "Sports Shoes".
 * Maps directly to the PostgreSQL table 'product_categories'.
 */
@Entity
@Table(name = "product_categories")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class ProductCategory {

    /**
     * Unique identifier for the category.
     * Auto-generated by PostgreSQL BIGSERIAL.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Name of the category (e.g., "Sports Rackets").
     */
    @Column(name = "name", nullable = false, length = 100)
    private String name;

    /**
     * Detailed description of what items belong in this category.
     */
    @Column(name = "description", columnDefinition = "TEXT")
    private String description;

    /**
     * Flag indicating whether this category is active and visible in the shop.
     * Defaults to true.
     */
    @Column(name = "is_active", nullable = false)
    @Builder.Default
    private Boolean isActive = true;

    /**
     * Timestamp when this category was created.
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * Timestamp when this category was last updated.
     */
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    /**
     * Auto-populate timestamps and default values before persisting.
     */
    @PrePersist
    protected void onCreate() {
        if (this.isActive == null) {
            this.isActive = true;
        }
        LocalDateTime now = LocalDateTime.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    /**
     * Auto-update the updated_at timestamp before modification.
     */
    @PreUpdate
    protected void onUpdate() {
        this.updatedAt = LocalDateTime.now();
    }
}
