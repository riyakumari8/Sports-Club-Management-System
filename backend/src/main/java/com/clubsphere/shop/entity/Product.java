package com.clubsphere.shop.entity;

import com.fasterxml.jackson.annotation.JsonIgnore;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.LocalDateTime;

/**
 * Product — Entity representing an individual merchandise item available in the Sports Shop.
 *
 * Maps directly to the PostgreSQL table 'products'.
 * Note: 'selling_price' is a GENERATED ALWAYS AS column in PostgreSQL,
 * computed as ROUND(original_price * (1 - discount_percent / 100.0), 2).
 * It is marked with insertable = false, updatable = false so JPA never includes it in DML statements.
 */
@Entity
@Table(name = "products")
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Product {

    /**
     * Unique identifier for the product.
     * Auto-generated by PostgreSQL BIGSERIAL.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Category that this product belongs to.
     * Fetched lazily for optimal performance.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "category_id", nullable = false)
    @JsonIgnore
    private ProductCategory category;

    /**
     * Read-only category ID mapping matching the category_id foreign key column.
     */
    @Column(name = "category_id", insertable = false, updatable = false)
    private Long categoryId;

    /**
     * Product name (e.g. "Yonex Astrox 88D Badminton Racket").
     */
    @Column(name = "name", nullable = false, length = 200)
    private String name;

    /**
     * Full product description and specifications.
     */
    @Column(name = "description", columnDefinition = "TEXT")
    private String description;

    /**
     * Primary display image URL for the product.
     */
    @Column(name = "image_url", columnDefinition = "TEXT")
    private String imageUrl;

    /**
     * Original retail price before any discounts.
     * Must be non-negative.
     */
    @Column(name = "original_price", nullable = false, precision = 10, scale = 2)
    private BigDecimal originalPrice;

    /**
     * Discount percentage applied to the original price (0.00 to 100.00).
     * Defaults to 0.00.
     */
    @Column(name = "discount_percent", nullable = false, precision = 5, scale = 2)
    @Builder.Default
    private BigDecimal discountPercent = BigDecimal.ZERO;

    /**
     * Effective selling price after discount.
     * GENERATED ALWAYS AS (ROUND(original_price * (1 - discount_percent / 100.0), 2)) STORED in DB.
     * DO NOT insert or update via JPA.
     */
    @Column(name = "selling_price", insertable = false, updatable = false, precision = 10, scale = 2)
    private BigDecimal sellingPrice;

    /**
     * Flag indicating whether the product is active for purchase.
     * Soft delete sets this to false. Defaults to true.
     */
    @Column(name = "is_active", nullable = false)
    @Builder.Default
    private Boolean isActive = true;

    /**
     * Timestamp when the product was created.
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * Timestamp when the product was last updated.
     */
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    /**
     * Helper to keep categoryId synchronized when setting category.
     */
    public void setCategory(ProductCategory category) {
        this.category = category;
        if (category != null) {
            this.categoryId = category.getId();
        }
    }

    /**
     * Returns the categoryId, preferring the entity association or the direct column.
     */
    public Long getCategoryId() {
        if (this.category != null) {
            return this.category.getId();
        }
        return this.categoryId;
    }

    /**
     * Calculates the expected selling price in Java.
     * Used as a fallback when the entity has just been inserted/updated in memory
     * before the database-generated column is re-queried.
     */
    public BigDecimal calculateSellingPrice() {
        if (this.originalPrice == null) {
            return BigDecimal.ZERO;
        }
        BigDecimal discount = this.discountPercent != null ? this.discountPercent : BigDecimal.ZERO;
        BigDecimal multiplier = BigDecimal.ONE.subtract(
                discount.divide(BigDecimal.valueOf(100), 4, RoundingMode.HALF_UP)
        );
        return this.originalPrice.multiply(multiplier).setScale(2, RoundingMode.HALF_UP);
    }

    /**
     * Auto-populate timestamps and defaults before persisting.
     */
    @PrePersist
    protected void onCreate() {
        if (this.isActive == null) {
            this.isActive = true;
        }
        if (this.discountPercent == null) {
            this.discountPercent = BigDecimal.ZERO;
        }
        if (this.category != null && this.categoryId == null) {
            this.categoryId = this.category.getId();
        }
        LocalDateTime now = LocalDateTime.now();
        this.createdAt = now;
        this.updatedAt = now;
    }

    /**
     * Auto-update the timestamp before updating.
     */
    @PreUpdate
    protected void onUpdate() {
        if (this.category != null) {
            this.categoryId = this.category.getId();
        }
        this.updatedAt = LocalDateTime.now();
    }
}
