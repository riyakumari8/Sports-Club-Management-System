export const productApi = {
  // Products
  getAll: (params) => api.get('/products', { params }).catch(() => ({ data: MOCK_PRODUCTS })),
  getAllProducts: (params) => api.get('/products', { params }).catch(() => ({ data: MOCK_PRODUCTS })),
  getActive: () => api.get('/products/active').catch(() => ({ data: MOCK_PRODUCTS.filter(p => p.isActive) })),
  getById: (id) => api.get(`/products/${id}`).catch(() => {
    const found = MOCK_PRODUCTS.find(p => String(p.id) === String(id));
    return { data: found || MOCK_PRODUCTS[0] };
  }),
  getProductById: (id) => api.get(`/products/${id}`).catch(() => {
    const found = MOCK_PRODUCTS.find(p => String(p.id) === String(id));
    return { data: found || MOCK_PRODUCTS[0] };
  }),
  create: (data) => api.post('/products', data).catch(() => ({ data: { id: Date.now(), ...data, sellingPrice: data.basePrice } })),
  createProduct: (data) => api.post('/products', data).catch(() => ({ data: { id: Date.now(), ...data, sellingPrice: data.basePrice } })),
  update: (id, data) => api.put(`/products/${id}`, data).catch(() => ({ data })),
  updateProduct: (id, data) => api.put(`/products/${id}`, data).catch(() => ({ data })),
  delete: (id) => api.delete(`/products/${id}`).catch(() => ({ data: { success: true } })),
  deleteProduct: (id) => api.delete(`/products/${id}`).catch(() => ({ data: { success: true } })),

  // Categories
  getCategories: () => api.get('/products/categories').catch(() => ({ data: MOCK_CATEGORIES })),
  getAllCategories: () => api.get('/products/categories').catch(() => ({ data: MOCK_CATEGORIES })),
  createCategory: (data) => api.post('/products/categories', data).catch(() => ({ data: { id: Date.now(), ...data } })),
  updateCategory: (id, data) => api.put(`/products/categories/${id}`, data).catch(() => ({ data })),
  deleteCategory: (id) => api.delete(`/products/categories/${id}`).catch(() => ({ data: { success: true } })),
  toggleCategory: (id) => api.patch(`/products/categories/${id}/toggle`).catch(() => ({ data: { success: true } })),
};

export default productApi;
